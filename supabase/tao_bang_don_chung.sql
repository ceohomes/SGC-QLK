  ma_don_chuyen_tiep_n_b  text,
  ghi_chu                 text,
  ghi_chu_vat_tu          text,
  trang_thai              text,
  nhan_hieu               text,
  ten_du_an               text,
  "tenDuAn"               text,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now()
);

-- Chỉ mục cho các truy vấn app hay dùng (lọc theo dự án, sắp theo thời gian, tra mã SAP)
CREATE INDEX IF NOT EXISTS don_chung_ten_du_an_idx ON public.don_chung (ten_du_an);
CREATE INDEX IF NOT EXISTS don_chung_du_an_idx     ON public.don_chung (du_an);
CREATE INDEX IF NOT EXISTS don_chung_updated_idx   ON public.don_chung (updated_at DESC);
CREATE INDEX IF NOT EXISTS don_chung_ma_sap_idx    ON public.don_chung (ma_s_a_p);

-- Tự cập nhật updated_at khi sửa dòng
CREATE OR REPLACE FUNCTION public.don_chung_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := now(); RETURN NEW; END $$;
DROP TRIGGER IF EXISTS don_chung_touch ON public.don_chung;
CREATE TRIGGER don_chung_touch BEFORE UPDATE ON public.don_chung
  FOR EACH ROW EXECUTE FUNCTION public.don_chung_touch();

-- Quyền truy cập: giống các bảng khác của app (đọc/ghi công khai bằng anon key).
-- Lưu ý bảo mật: ai có link web cũng đọc/ghi được bảng này.
ALTER TABLE public.don_chung ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public don_chung" ON public.don_chung;
CREATE POLICY "Allow public don_chung" ON public.don_chung FOR ALL USING (true) WITH CHECK (true);
