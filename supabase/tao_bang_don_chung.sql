-- CHƯA CHẠY. Lưu ý trước khi chạy:
--   App hiện để Đơn chung ở chế độ "chỉ lưu trên máy" (offline-first): khi tải file lên,
--   app KHÔNG ghi lên bảng này (xem syncRowsToSupabase trong src/App.jsx).
--   Tạo bảng xong mà chưa sửa app để ghi dữ liệu lên thì bảng sẽ trống, và lúc mở trang
--   app có thể lấy bảng trống thay cho dữ liệu đang có trong trình duyệt.
--   => Chỉ chạy khi đã quyết làm tiếp phần đồng bộ Đơn chung lên Supabase
--      và bật lại dòng tải bảng (USE_REMOTE_DON_CHUNG = true trong src/App.jsx).
-- Cách chạy: Supabase Dashboard -> dự án ojknvcprfwcrnydkspqp -> SQL Editor -> New query -> dán -> Run.

