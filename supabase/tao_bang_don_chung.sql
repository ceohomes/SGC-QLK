  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ngay_xuat_nhap          text,
  ma_vat_tu               text,
  ma_s_a_p                text,
  thong_so_ky_thuat       text,
  ten_vat_tu              text,
  dvt                     text,
  loai_don                text,
  ma_don_nhap_kho         text,
  ma_don_xuat_kho         text,
  khoi_luong_nhap         numeric,
  ma_don_vi_giao          text,
  don_vi_giao             text,
  nguoi_giao              text,
  khoi_luong_xuat         numeric,
  ma_don_vi_nhan          text,
  don_vi_nhan             text,
  nguoi_phe_duyet         text,
  ten_nguon               text,
  ma_nguon                text,
  lo                      text,
  hang_muc                text,
  so_hop_dong             text,
  thu_kho                 text,
  bien_so_xe              text,
  phan_khu                text,
  du_an                   text,
  tinh_trang              text,
  nguoi_nhan              text,
